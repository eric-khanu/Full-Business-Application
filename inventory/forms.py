# Product
# =====================================================================
class ProductForm(TailwindMixin, forms.ModelForm):
    class Meta:
        model = Product
        # FIX: only real fields. `sku` and `barcode` are read-only here
        # because they're auto-generated by Product.save().
        fields = [
            # Naming
            "name", "strength", "form",
            # Classification
            "category", "supplier", "is_medicine",
            # Media
            "image",
            # Pricing
            "cost_price", "selling_price",
            # Pack
            "pack_size", "unit",
            # Medicine flags
            "is_prescription", "is_controlled",
            # Stock
            "quantity", "reorder_level", "expiry_date", "is_active",
        ]
        widgets = {
            "expiry_date": forms.DateInput(attrs={"type": "date"}),
        }

    # ---- Field groupings for the template ----
    NAMING_FIELDS = ("name", "strength", "form")
    CLASSIFICATION_FIELDS = ("category", "supplier", "is_medicine")
    PRICING_FIELDS = ("cost_price", "selling_price")
    PACK_FIELDS = ("pack_size", "unit")
    FLAG_FIELDS = ("is_prescription", "is_controlled")
    STOCK_FIELDS = ("quantity", "reorder_level", "expiry_date")
    STATUS_FIELDS = ("is_active",)

    def naming_fields(self):
        return [self[n] for n in self.NAMING_FIELDS if n in self.fields]

    def classification_fields(self):
        return [self[n] for n in self.CLASSIFICATION_FIELDS if n in self.fields]

    def pricing_fields(self):
        return [self[n] for n in self.PRICING_FIELDS if n in self.fields]

    def pack_fields(self):
        return [self[n] for n in self.PACK_FIELDS if n in self.fields]

    def flag_fields(self):
        return [self[n] for n in self.FLAG_FIELDS if n in self.fields]

    def stock_fields(self):
        return [self[n] for n in self.STOCK_FIELDS if n in self.fields]

    def status_fields(self):
        return [self[n] for n in self.STATUS_FIELDS if n in self.fields]

    # ---- Init ----
    def __init__(self, *args, business=None, **kwargs):
        self.business = business
        super().__init__(*args, **kwargs)

        if business:
            self.fields["category"].queryset = (
                business.categories.all().order_by("kind", "name")
            )
            self.fields["supplier"].queryset = (
                business.suppliers.filter(is_active=True)
            )

        self.fields["category"].empty_label = "— Select category —"
        self.fields["supplier"].empty_label = "— Select supplier —"

        # Optional fields
        for name in ("category", "supplier", "strength", "expiry_date"):
            self.fields[name].required = False

        # Boolean flags
        for name in ("is_medicine", "is_prescription",
                     "is_controlled", "is_active"):
            self.fields[name].required = False

        # Defaults on create
        if not self.instance.pk:
            self.fields["is_medicine"].initial = True
            self.fields["is_active"].initial = True
            self.fields["pack_size"].initial = 1

    # ---- Validation ----
    def clean_name(self):
        return (self.cleaned_data.get("name") or "").strip()

    def clean_strength(self):
        return (self.cleaned_data.get("strength") or "").strip()

    def clean(self):
        cleaned = super().clean()

        # Price sanity
        cost = cleaned.get("cost_price")
        sell = cleaned.get("selling_price")
        if cost is not None and sell is not None and sell < cost:
            self.add_error(
                "selling_price",
                "Selling price should not be below cost price.",
            )

        # Non-medicine products shouldn't be prescription or controlled
        is_medicine = cleaned.get("is_medicine")
        if not is_medicine:
            if cleaned.get("is_prescription"):
                self.add_error(
                    "is_prescription",
                    "Only medicines can be prescription-only.",
                )
            if cleaned.get("is_controlled"):
                self.add_error(
                    "is_controlled",
                    "Only medicines can be controlled substances.",
                )

        # Expiry date sanity
        expiry = cleaned.get("expiry_date")
        if expiry and expiry < timezone.localdate():
            self.add_error(
                "expiry_date",
                "Expiry date cannot be in the past.",
            )

        return cleaned


