# Stock adjustment
# =====================================================================
class StockAdjustForm(TailwindMixin, forms.Form):
    """
    Stock adjustment form.

    Mode choices come from `StockMovement.MovementType` plus the
    special "set" (absolute stock count) mode handled by services.py.
    """

    # Build choices dynamically so this always matches the model
    MODE_CHOICES = [
        (StockMovement.MovementType.IN,        "Received (add stock)"),
        (StockMovement.MovementType.OUT,       "Dispensed (sold / issued)"),
        (StockMovement.MovementType.ADJUST,    "Adjustment (loss / damage)"),
        (StockMovement.MovementType.EXPIRED,   "Expired / disposed"),
        (StockMovement.MovementType.RETURN,    "Return to supplier"),
        ("set",                                "Set exact quantity (stock count)"),
    ]

    mode = forms.ChoiceField(
        choices=MODE_CHOICES,
        initial=StockMovement.MovementType.IN,
        widget=forms.RadioSelect,
        label="Operation",
    )
    quantity = forms.IntegerField(
        min_value=0,
        label="Quantity",
    )
    reason = forms.CharField(
        max_length=200, required=False,
        label="Reason",
        widget=forms.TextInput(attrs={
            "placeholder": "e.g. Purchase order, damaged in transit",
        }),
    )
    reference = forms.CharField(
        max_length=100, required=False,
        label="Reference",
        help_text="PO number, invoice number, etc.",
    )